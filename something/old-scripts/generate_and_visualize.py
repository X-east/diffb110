from ddpo.integration.diffsbdd_model import DiffSBDDModel
from DiffSBDD.constants import dataset_params


def save_molecule_xyz(coords, atom_types, atom_decoder, filename):
    """Save molecule in XYZ format for visualization"""
    n_atoms = len(coords)
    
    with open(filename, 'w') as f:
        f.write(f"{n_atoms}\n")
        f.write(f"Generated molecule\n")
        for i, (coord, atom_idx) in enumerate(zip(coords, atom_types)):
            atom_symbol = atom_decoder[atom_idx]
            x, y, z = coord
            f.write(f"{atom_symbol:2s} {x:12.6f} {y:12.6f} {z:12.6f}\n")
    
    print(f"  Saved: {filename}")


def save_molecule_sdf(coords, atom_types, atom_decoder, filename):
    """Save molecule in SDF format using RDKit"""
    try:
        from rdkit import Chem
        from rdkit.Chem import AllChem
        
        # Create RDKit molecule
        mol = Chem.RWMol()
        
        # Add atoms
        for atom_idx in atom_types:
            atom_symbol = atom_decoder[atom_idx]
            atom = Chem.Atom(atom_symbol)
            mol.AddAtom(atom)
        
        # Add conformer (3D coordinates)
        conf = Chem.Conformer(len(coords))
        for i, coord in enumerate(coords):
            conf.SetAtomPosition(i, tuple(coord))
        mol.AddConformer(conf)
        
        # Convert to Mol object
        mol = mol.GetMol()
        
        # Try to infer bonds based on distances
        AllChem.DetermineBonds(mol)
        
        # Write SDF
        writer = Chem.SDWriter(filename)
        writer.write(mol)
        writer.close()
        
        print(f"  Saved: {filename}")
        return True
        
    except ImportError:
        print(f"  Warning: RDKit not available, skipping SDF generation")
        return False
    except Exception as e:
        print(f"  Warning: Failed to save SDF: {e}")
        return False


def save_molecule_pdb(coords, atom_types, atom_decoder, filename):
    """Save molecule in PDB format"""
    with open(filename, 'w') as f:
        f.write("REMARK   Generated by DiffSBDDModel\n")
        for i, (coord, atom_idx) in enumerate(zip(coords, atom_types)):
            atom_symbol = atom_decoder[atom_idx]
            x, y, z = coord
            # PDB format: ATOM serial name resName chainID resSeq x y z occupancy tempFactor element
            f.write(f"HETATM{i+1:5d}  {atom_symbol:2s}  LIG A   1    "
                   f"{x:8.3f}{y:8.3f}{z:8.3f}  1.00  0.00          {atom_symbol:>2s}\n")
        f.write("END\n")
    
    print(f"  Saved: {filename}")



def save_trajectory_data(output_dir, latents, logps, timesteps_list, mus, sigmas, node_mask, edge_mask):
    """Save all trajectory data for DDPO training analysis"""
    import json
    
    traj_dir = output_dir / "trajectory_data"
    traj_dir.mkdir(exist_ok=True)
    
    # Save as numpy arrays
    np.save(traj_dir / "latents.npy", [l.cpu().numpy() for l in latents])
    np.save(traj_dir / "logps.npy", [l.cpu().numpy() for l in logps])
    np.save(traj_dir / "timesteps.npy", np.array(timesteps_list))
    np.save(traj_dir / "mus.npy", [m.cpu().numpy() for m in mus])
    np.save(traj_dir / "sigmas.npy", [s.cpu().numpy() for s in sigmas])
    np.save(traj_dir / "node_mask.npy", node_mask.cpu().numpy())
    np.save(traj_dir / "edge_mask.npy", edge_mask.cpu().numpy())
    
    # Save metadata as JSON
    metadata = {
        "n_timesteps": len(latents),
        "timesteps": timesteps_list,
        "latent_shapes": [list(l.shape) for l in latents],
        "logp_shapes": [list(l.shape) for l in logps],
        "node_mask_shape": list(node_mask.shape),
        "edge_mask_shape": list(edge_mask.shape),
    }
    with open(traj_dir / "metadata.json", 'w') as f:
        json.dump(metadata, f, indent=2)
    
    print(f"  Saved trajectory data to: {traj_dir}")
    print(f"    - latents: {len(latents)} steps")
    print(f"    - logps: {len(logps)} steps")
    print(f"    - mus: {len(mus)} steps")
    print(f"    - sigmas: {len(sigmas)} steps")


def generate_molecules(n_samples=10, timesteps=100, max_nodes=30):
    """Generate molecules and save them"""
    import sys
    
    print("="*70, flush=True)
    print("  DiffSBDD Molecule Generation", flush=True)
    print("="*70, flush=True)
    
    # Create output directory
    output_dir = Path("generated_molecules")
    output_dir.mkdir(exist_ok=True)
    print(f"\nOutput directory: {output_dir}", flush=True)
    
    # Load model
    print("\n[1/5] Loading DiffSBDDModel...", flush=True)
    model = DiffSBDDModel(
        checkpoint_path="DiffSBDD/checkpoints/crossdocked_fullatom_cond.ckpt",
        pocket_pdb_path="data/8GJJ-C-Cip.pdb",
        ref_ligand_path="C:1101",
        device="cpu",
        dataset_name="crossdock"
    )
    model.eval()
    
    print(f"  Model loaded successfully", flush=True)
    print(f"  - Timesteps: {model.T}", flush=True)
    print(f"  - Atom types: {model.atom_nf}", flush=True)
    print(f"  - Pocket residues: {len(model.residues)}", flush=True)
    
    # Get atom decoder
    dataset_info = dataset_params['crossdock']
    atom_decoder = dataset_info['atom_decoder']
    print(f"  - Atom decoder: {atom_decoder}", flush=True)
    
    # Prepare node counts (varying sizes)
    print(f"\n[2/5] Preparing to generate {n_samples} molecules...", flush=True)
    node_counts = []
    for i in range(n_samples):
        # Vary molecule size between 10-25 atoms
        n_nodes = np.random.randint(10, min(26, max_nodes + 1))
        node_counts.append(n_nodes)
    
    print(f"  Molecule sizes: {node_counts}", flush=True)
    
    # Create node_mask and edge_mask
    batch_size = n_samples
    nodesxsample = torch.tensor(node_counts)
    node_mask, edge_mask = model.get_mask(nodesxsample, batch_size, max_nodes)
    
    # Generate molecules
    print(f"\n[3/5] Generating molecules (timesteps={timesteps})...", flush=True)
    print(f"  Batch size: {batch_size}, Max nodes: {max_nodes}", flush=True)
    print(f"  Starting diffusion sampling...", flush=True)
    sys.stdout.flush()
    
    import time
    start_time = time.time()
    
    with torch.no_grad():
        x, h, latents, logps, timesteps_list, mus, sigmas = model.sample(
            n_samples=batch_size,
            n_nodes=nodesxsample,
            node_mask=node_mask,
            edge_mask=edge_mask,
            fix_noise=False,
            timestep=timesteps
        )
    
    elapsed = time.time() - start_time
    print(f"\n  Generation complete! (took {elapsed:.1f}s)")
    
    print(f"  Generation complete!")
    print(f"  - Generated {batch_size} molecules")
    print(f"  - Trajectory length: {len(latents)}")
    print(f"  - Final x shape: {x.shape}")
    print(f"  - Final h shape: {h['categorical'].shape}")
    
    # Save trajectory data (latents, logps, mus, sigmas)
    print(f"\n[4/5] Saving trajectory data...")
    save_trajectory_data(output_dir, latents, logps, timesteps_list, mus, sigmas, node_mask, edge_mask)
    
    # Save molecules
    print(f"\n[5/5] Saving molecules...")
    
    stats = {
        'total': 0,
        'by_size': {},
        'by_atom_type': {}
    }
    
    for i in range(batch_size):
        n_atoms = node_counts[i]
        
        # Extract coordinates and atom types
        coords = x[i, :n_atoms].cpu().numpy()
        atom_type_probs = h['categorical'][i, :n_atoms].cpu().numpy()
        atom_types = np.argmax(atom_type_probs, axis=-1)
        
        # Decode atom types
        atom_symbols = [atom_decoder[idx] for idx in atom_types]
        
        # Statistics
        stats['total'] += 1
        stats['by_size'][n_atoms] = stats['by_size'].get(n_atoms, 0) + 1
        for symbol in atom_symbols:
            stats['by_atom_type'][symbol] = stats['by_atom_type'].get(symbol, 0) + 1
        
        # Create molecule directory
        mol_dir = output_dir / f"molecule_{i+1:03d}"
        mol_dir.mkdir(exist_ok=True)
        
        # Save in multiple formats
        print(f"\n  Molecule {i+1}/{batch_size}:")
        print(f"    Atoms: {n_atoms}")
        print(f"    Types: {' '.join(atom_symbols)}")
        print(f"    Coord range: [{coords.min():.2f}, {coords.max():.2f}]")
        
        # XYZ format (always works)
        save_molecule_xyz(
            coords, atom_types, atom_decoder,
            mol_dir / f"molecule_{i+1:03d}.xyz"
        )
        
        # PDB format
        save_molecule_pdb(
            coords, atom_types, atom_decoder,
            mol_dir / f"molecule_{i+1:03d}.pdb"
        )
        
        # SDF format (if RDKit available)
        save_molecule_sdf(
            coords, atom_types, atom_decoder,
            mol_dir / f"molecule_{i+1:03d}.sdf"
        )
        
        # Save metadata
        with open(mol_dir / "metadata.txt", 'w') as f:
            f.write(f"Molecule {i+1}\n")
            f.write(f"="*50 + "\n")
            f.write(f"Number of atoms: {n_atoms}\n")
            f.write(f"Atom types: {' '.join(atom_symbols)}\n")
            f.write(f"Coordinate range: [{coords.min():.3f}, {coords.max():.3f}]\n")
            f.write(f"Center of geometry: {coords.mean(axis=0)}\n")
            f.write(f"\nAtom details:\n")
            for j, (symbol, coord) in enumerate(zip(atom_symbols, coords)):
                f.write(f"  {j+1:3d}. {symbol:2s}  {coord[0]:8.3f} {coord[1]:8.3f} {coord[2]:8.3f}\n")
        
        # Save per-molecule numpy data
        np.save(mol_dir / "coords.npy", coords)
        np.save(mol_dir / "atom_types.npy", atom_types)
        np.save(mol_dir / "atom_type_probs.npy", atom_type_probs)
    
    # Save batch-level data
    batch_dir = output_dir / "batch_data"
    batch_dir.mkdir(exist_ok=True)
    np.save(batch_dir / "x_final.npy", x.cpu().numpy())
    np.save(batch_dir / "h_categorical.npy", h['categorical'].cpu().numpy())
    np.save(batch_dir / "node_counts.npy", np.array(node_counts))
    print(f"\n  Saved batch data to: {batch_dir}")
    
    # Print summary
    print("\n" + "="*70)
    print("  Generation Summary")
    print("="*70)
    print(f"\nTotal molecules generated: {stats['total']}")
    print(f"\nMolecule size distribution:")
    for size in sorted(stats['by_size'].keys()):
        count = stats['by_size'][size]
        print(f"  {size:2d} atoms: {count:2d} molecules")
    
    print(f"\nAtom type distribution:")
    for atom_type in sorted(stats['by_atom_type'].keys()):
        count = stats['by_atom_type'][atom_type]
        print(f"  {atom_type:2s}: {count:3d} atoms")
    
    print(f"\nOutput directory: {output_dir.absolute()}")
    print(f"\nVisualization:")
    print(f"  - Open .xyz files with: Avogadro, VMD, PyMOL")
    print(f"  - Open .pdb files with: PyMOL, Chimera, VMD")
    print(f"  - Open .sdf files with: RDKit, PyMOL, Avogadro")
    
    return output_dir


def main():
    parser = argparse.ArgumentParser(
        description="Generate molecules with DiffSBDDModel"
    )
    parser.add_argument(
        "--n_samples", type=int, default=10,
        help="Number of molecules to generate (default: 10)"
    )
    parser.add_argument(
        "--timesteps", type=int, default=100,
        help="Number of diffusion timesteps (default: 100, max: 500)"
    )
    parser.add_argument(
        "--max_nodes", type=int, default=30,
        help="Maximum number of atoms per molecule (default: 30)"
    )
    
    args = parser.parse_args()
    
    try:
        output_dir = generate_molecules(
            n_samples=args.n_samples,
            timesteps=args.timesteps,
            max_nodes=args.max_nodes
        )
        
        print("\n" + "="*70)
        print("  [SUCCESS] Molecule generation complete!")
        print("="*70)
        
    except KeyboardInterrupt:
        print("\n\n  [WARNING] Generation interrupted by user")
        sys.exit(1)
    except Exception as e:
        print(f"\n\n  [ERROR] Generation failed: {e}")
        import traceback
        traceback.print_exc()
        sys.exit(1)


if __name__ == "__main__":
    main()
